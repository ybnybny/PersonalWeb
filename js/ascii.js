// =====================================================================
// ascii.js — 主房间物件字符画
// 只用单宽字符（ASCII + 制表符 + 方块字符），不含中文/emoji，保证对齐
// =====================================================================

function box(inner, w) {
  return [
    '┌' + '─'.repeat(w) + '┐',
    ...inner.map((l) => '│' + l.padEnd(w) + '│'),
    '└' + '─'.repeat(w) + '┘',
  ];
}

function dbox(inner, w) {
  return [
    '╔' + '═'.repeat(w) + '╗',
    ...inner.map((l) => '║' + l.padEnd(w) + '║'),
    '╚' + '═'.repeat(w) + '╝',
  ];
}

